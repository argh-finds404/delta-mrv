// The eval (docs/10-FORENSICS.md §8): the labelled fixture classes through the real dHash and the
// real threshold. The expected matches must match, unrelated scenes must not, and the known
// misses (heavy crop, rotation) are measured and printed, not hidden. Lives with the
// integration tests only because the service module needs a configured environment.
import { writeFile } from "node:fs/promises";
import { afterAll, describe, expect, it } from "vitest";
import { hammingDistance } from "../../src/lib/forensics/dhash";
import { EVAL } from "../../src/lib/forensics/eval-results";
import { dHashOf, PERCEPTUAL_THRESHOLD } from "../../src/server/services/forensics.service";
import { LIFE, photo, VARIANTS } from "../fixtures/forensics/images";
import { client } from "./db";

afterAll(() => client.end());

// The published result (/trust) is src/lib/forensics/eval-results.ts. docs/10 §8 hoped crops of
// 10% would match; they do not (distances 8–13), and one 50% resize sits exactly on the
// threshold. If the pipeline drifts, this goes red: re-run the eval and re-publish, never
// quietly re-baseline.
const MEASURED_MATCHES = Object.fromEntries(EVAL.classes.map((c) => [c.key, [c.matched, c.of]]));

describe("forensics eval", () => {
  it("recompression always matches, a different scene never does, and the misses are the measured ones", async () => {
    const names = Object.keys(LIFE) as (keyof typeof LIFE)[];
    const base = Object.fromEntries(await Promise.all(names.map(async (n) => [n, await photo(n)] as const))) as Record<keyof typeof LIFE, Buffer>;
    const hash = Object.fromEntries(await Promise.all(names.map(async (n) => [n, await dHashOf(base[n])] as const))) as Record<keyof typeof LIFE, string>;

    const rows: { photo: string; variant: string; distance: number; match: boolean }[] = [];
    for (const n of names) {
      for (const [variant, edit] of Object.entries(VARIANTS)) {
        const distance = hammingDistance(hash[n], await dHashOf(await edit(base[n])));
        rows.push({ photo: n, variant, distance, match: distance < PERCEPTUAL_THRESHOLD });
      }
      for (const other of names.filter((o) => o !== n)) {
        const distance = hammingDistance(hash[n], hash[other]);
        rows.push({ photo: n, variant: `different scene (${other})`, distance, match: distance < PERCEPTUAL_THRESHOLD });
      }
    }
    console.table(rows);

    const counted: Record<string, [number, number]> = {};
    for (const r of rows) {
      const cls = r.variant.startsWith("different scene") ? "different scene" : r.variant;
      const [m, n] = counted[cls] ?? [0, 0];
      counted[cls] = [m + (r.match ? 1 : 0), n + 1];
    }
    expect(counted).toEqual(MEASURED_MATCHES);
    expect(EVAL.threshold).toBe(PERCEPTUAL_THRESHOLD);
    // pnpm eval:forensics: the same run, written up. Only after the assertions, so the
    // document can never hold numbers the published table does not.
    if (process.env.WRITE_FORENSIC_EVAL) await writeFile("docs/FORENSIC_EVAL.md", report(rows));
  });
});

function report(rows: { photo: string; variant: string; distance: number; match: boolean }[]): string {
  const copies = rows.filter((r) => !r.variant.startsWith("different scene"));
  const strangers = rows.filter((r) => r.variant.startsWith("different scene"));
  const meant = new Set<string>(EVAL.classes.filter((c) => c.expect === "match").map((c) => c.key));
  const [tp, fp] = [copies.filter((r) => r.match).length, strangers.filter((r) => r.match).length];
  const meantRows = copies.filter((r) => meant.has(r.variant));
  const pct = (a: number, b: number) => (b ? `${Math.round((100 * a) / b)}% (${a} of ${b})` : "not defined (nothing matched)");
  return `# Forensic evaluation

Generated by \`pnpm eval:forensics\` (\`test/integration/forensics-eval.test.ts\`). Do not edit by
hand: re-run it. The integration suite re-measures this on every run and fails if the counts
differ from \`src/lib/forensics/eval-results.ts\`, which is what \`/trust\` publishes.

Measured ${EVAL.measuredOn}. Fingerprint: 64-bit dHash. Two files match when their Hamming
distance is under ${PERCEPTUAL_THRESHOLD}. Sample: ${EVAL.sample} Three photographs is a small
sample. Read this as a description of the fingerprint's behaviour, not as a guarantee.

## Result

| | |
|---|---|
| Precision (matches that were real copies) | ${pct(tp, tp + fp)} |
| Recall over edits the spec expects to match (resize, re-compression, 10% crop) | ${pct(meantRows.filter((r) => r.match).length, meantRows.length)} |
| Recall over every edited copy, including the expected misses | ${pct(tp, copies.length)} |
| False matches between different photographs | ${fp} of ${strangers.length} |

## By class

| Edit | Expected | Matched | Note |
|---|---|---|---|
${EVAL.classes.map((c) => `| ${c.label} | ${c.expect} | ${c.matched} of ${c.of} | ${c.note} |`).join("\n")}

## Known misses, stated plainly

- **Cropping defeats it.** \`docs/10-FORENSICS.md\` §8 expected a 10% crop to match. It does not.
- **Rotation defeats it.** dHash is not rotation-invariant.
- **A resize can land on the threshold.** One 50% resize measured exactly ${PERCEPTUAL_THRESHOLD} and was missed.

Someone who crops or rotates a reused photograph gets past this check. The exact SHA-256 check
only catches byte-identical files. That is why a finding is a signal for two independent human
reviewers and never a verdict.

## Not measured here

The two database-backed classes of §8 are asserted by \`test/integration/forensics.test.ts\`
and have no rate to report: an unmodified photograph raises no duplicate finding, and a
known cross-project duplicate raises a \`HIGH\` finding.

## Every pair

| Photograph | Edit | Hamming distance | Match |
|---|---|---|---|
${rows.map((r) => `| ${r.photo} | ${r.variant} | ${r.distance} | ${r.match ? "yes" : "no"} |`).join("\n")}
`;
}
